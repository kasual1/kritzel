const DEFAULT_OUTPUT = path.join(
  __dirname,
  '../libs/engine/core/src/classes/registries/default-icons.ts',
);
const MATERIAL_SYMBOLS_BASE_URL =
  'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined';

function getIconUrl(iconName) {
  return `${MATERIAL_SYMBOLS_BASE_URL}/${encodeURIComponent(iconName)}/default/24px.svg`;
}

async function fetchIcon(iconName) {
  const url = getIconUrl(iconName);
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`${iconName}: ${response.status} ${response.statusText} (${url})`);
  }

  const svg = await response.text();
  if (!/^\s*<svg\b/i.test(svg)) {
    throw new Error(`${iconName}: Google returned a non-SVG response (${url})`);
  }

  const optimizedSvg = optimize(svg, {
    plugins: ['preset-default'],
    js2svg: { pretty: false },
  }).data;
  return optimizedSvg.replace('<svg ', '<svg fill="currentColor" ');
}

function createTypeScriptFile(icons) {
  const entries = icons.map(
    ([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`,
  );

  return [
    '// Generated by scripts/generate-google-font-icons.js. Do not edit manually.',
    '',
    'export const defaultIcons: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

async function main() {
  const outputPath = path.resolve(process.argv[2] || DEFAULT_OUTPUT);
  const mappedIcons = Object.entries(ICONS).filter(([, iconName]) => iconName !== null);
  const skippedIcons = Object.entries(ICONS)
    .filter(([, iconName]) => iconName === null)
    .map(([name]) => name);

  const icons = await Promise.all(
    mappedIcons.map(async ([name, iconName]) => [name, await fetchIcon(iconName)]),
  );

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, createTypeScriptFile(icons), 'utf8');

  console.log(`Generated ${icons.length} icons in ${outputPath}`);
  if (skippedIcons.length > 0) {
    console.log(`Skipped icons without a Google Fonts mapping: ${skippedIcons.join(', ')}`);
  }
}

main().catch((error) => {
  console.error(`Icon generation failed: ${error.message}`);
  process.exitCode = 1;
});