import { KritzelPoint } from './point.interface';

/**
 * A rectangle in the coordinates of an object's content, in CSS pixels relative to the top-left corner of the
 * content (for a `KritzelIframeObject`, the iframe's viewport), before canvas zoom, object scale and rotation.
 */
export interface KritzelObjectElementRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

/**
 * Serializable description of an element inside an object's content, for example an element of the page
 * rendered by a `KritzelIframeObject`. DOM nodes can't leave the content, so this is what the engine reports.
 *
 * The content describes its own elements, and it may be untrusted (e.g. generated by an LLM): treat every string,
 * such as `text` or an `href` attribute, as untrusted data, never as HTML or a trusted URL.
 */
export interface KritzelObjectElementInfo {
  /**
   * A CSS selector that matched exactly this element when it was reported. Pass it back to highlight the
   * element, query it again or point an agent's cursor at it (`agent.moveTo({ objectId, selector })`).
   * Selectors built from a `data-kritzel-id` or an `id` survive regenerated content; positional ones
   * (`:nth-of-type`) may point elsewhere once the content changes.
   */
  selector: string;
  /** Value of the element's `data-kritzel-id` attribute: a stable identifier content authors can assign. */
  kritzelId?: string;
  /** Lowercase tag name, e.g. `'button'`. */
  tagName: string;
  /** The element's `id` attribute. */
  id?: string;
  /** The element's classes. */
  classList: string[];
  /** The element's text with collapsed whitespace, truncated to 200 characters. Omitted when empty. */
  text?: string;
  /**
   * Descriptive attributes: `role`, `aria-*`, `data-*`, `name`, `type`, `href`, `src`, `alt`, `title`,
   * `placeholder` and `for`, each truncated to 200 characters. Form field values are never included here, see `value`.
   */
  attributes: Record<string, string>;
  /** State the attributes don't show, e.g. whether a checkbox is checked. Omitted when there is none. */
  state?: KritzelObjectElementState;
  /**
   * The current value of a form field (input, textarea, select), truncated to 500 characters. Only reported by
   * `queryElements()` with `includeValues` and by `interactWithElement()`; never for password fields.
   */
  value?: string;
  /** The element's bounding box in content coordinates when it was reported. */
  rect: KritzelObjectElementRect;
  /**
   * The part of `rect` that can be seen: clipped by scrolling containers and the content's viewport. Omitted when
   * nothing of the element can be seen, e.g. with `display: none`, `visibility: hidden` or scrolled out of view.
   */
  visibleRect?: KritzelObjectElementRect;
}

/** State of an element inside an object's content that its attributes don't show. Only applicable fields are set. */
export interface KritzelObjectElementState {
  /** The element is disabled (`disabled`, `aria-disabled="true"` or inside an `inert` subtree). */
  disabled?: boolean;
  /** Whether a checkbox, radio button or switch (also by ARIA role) is checked; `'mixed'` when indeterminate. */
  checked?: boolean | 'mixed';
  /** Whether an `<option>` is selected. */
  selected?: boolean;
  /** Whether a `<details>` element is open. */
  open?: boolean;
  /** The element has the keyboard focus inside the content. */
  focused?: boolean;
  /** Whether a text field, select or editable element can be filled. Set only on such elements. */
  editable?: boolean;
  /** Whether an `<audio>` or `<video>` element is playing. */
  playing?: boolean;
}

/** Options for `queryElements()`. */
export interface KritzelObjectElementQueryOptions {
  /** Maximum number of elements, 1 to 500. Defaults to 100. */
  limit?: number;
  /**
   * Only elements a user can interact with: links, buttons, form fields, elements with an interactive ARIA role,
   * `contenteditable`, `tabindex` or `onclick`, and elements that show a pointer cursor of their own.
   */
  interactiveOnly?: boolean;
  /** Includes the `value` of form fields, except password fields. Defaults to `false`. */
  includeValues?: boolean;
}

/**
 * Something done to an element inside an object's content, as a user would with the mouse or keyboard. Performed by
 * dispatching DOM events in the content: its handlers run as for a real press, but the events are not trusted
 * (`isTrusted` is `false`) and carry no user activation, so APIs that need a user gesture may refuse to work from
 * them. CSS `:hover` and `:active` styles don't apply.
 */
export type KritzelObjectElementInteraction =
  /** Moves the pointer onto the element and clicks it at the center of its visible part. */
  | { type: 'click'; /** `2` double-clicks. Defaults to `1`. */ count?: 1 | 2 }
  /** Moves the pointer onto the element (pointer and mouse over, enter and move events). */
  | { type: 'hover' }
  /**
   * Replaces the value of a text field, textarea or contenteditable element, sets a range, number, date or color
   * field, or selects the option of a select whose value or label matches. Fires `input` and `change`.
   */
  | { type: 'fill'; value: string }
  /** Checks or unchecks a checkbox, radio button or switch by clicking it (or its label) if needed. */
  | { type: 'check'; /** Defaults to `true`. */ checked?: boolean }
  /**
   * Focuses the element and presses a key, e.g. `'Enter'`, `'Escape'`, `'ArrowUp'`, `'a'` or `'Control+a'`. Enter and
   * Space activate buttons and links, arrow keys step range and number fields; no text is typed (use `'fill'`).
   */
  | { type: 'press'; key: string }
  /** Turns the mouse wheel over the element and scrolls it, or its closest scrollable ancestor, by CSS pixels. */
  | { type: 'scroll'; deltaX?: number; deltaY?: number };

/** The `type` of an element interaction. */
export type KritzelObjectElementInteractionType = KritzelObjectElementInteraction['type'];

/** Options for `interactWithElement()`. */
export interface KritzelObjectElementInteractionOptions {
  /**
   * Only checks that the interaction can be performed: scrolls the element into view and checks that it is
   * visible, enabled and not covered, without performing it. Defaults to `false`.
   */
  trial?: boolean;
}

/** Why an element interaction did not complete. */
export type KritzelObjectElementInteractionFailureReason =
  /** No element matches the selector. */
  | 'not-found'
  /** The element is not rendered, hidden or outside the content, also after scrolling it into view. */
  | 'not-visible'
  /** The element is disabled. */
  | 'disabled'
  /** Another element covers the point that would be clicked; see `coveredBy`. */
  | 'covered'
  /** `'fill'` on an element that is not a text field, select or editable element, or that is read-only. */
  | 'not-editable'
  /** `'check'` on an element that is not a checkbox, radio button or switch, or that did not change. */
  | 'not-checkable'
  /** `'scroll'` found nothing under the element that can scroll in that direction. */
  | 'not-scrollable'
  /** The value, option or key was not accepted. A field that refused a value is left as it was. */
  | 'invalid-value'
  /** The content is not reachable: the object isn't mounted, its content runs without scripts, didn't respond or reloaded. */
  | 'unavailable';

/** Result of `interactWithElement()`. Reported by the content, which may be untrusted. */
export interface KritzelObjectElementInteractionResult {
  /** `true` when the interaction was performed (or, with `trial`, could be performed). */
  completed: boolean;
  /** Set only when `completed` is `false`. */
  reason?: KritzelObjectElementInteractionFailureReason;
  /** What went wrong, in words. */
  message?: string;
  /** The element as it is after the interaction, with its `value`, once the content had a moment to react. */
  element?: KritzelObjectElementInfo;
  /** The element on top, for `'covered'`. */
  coveredBy?: KritzelObjectElementInfo;
}

/** A highlight drawn over elements inside an object's content. */
export interface KritzelObjectElementHighlight {
  /** CSS selector of the elements to highlight. Every match is highlighted, up to 100 elements. */
  selector: string;
  /** Any CSS color. Defaults to the theme's `elementHighlight.color`. */
  color?: string;
  /** Text shown above each highlighted element. */
  label?: string;
}

/** Options for picking elements inside an object's content. */
export interface KritzelObjectElementPickingOptions {
  /**
   * Limits picking to elements that match this CSS selector, e.g. `'[data-kritzel-id]'`. The closest matching
   * ancestor of the element under the pointer is used, and content outside any match can't be picked.
   */
  selector?: string;
  /** Color of the highlight that follows the pointer while picking. Defaults to the theme's `elementHighlight.color`. */
  color?: string;
}

/** State of the modifier keys during a pointer interaction. */
export interface KritzelObjectElementModifiers {
  shiftKey: boolean;
  ctrlKey: boolean;
  altKey: boolean;
  metaKey: boolean;
}

/** Emitted when the pointer moves onto another element inside an interactive object's content. */
export interface KritzelObjectElementHoverEvent {
  /** ID of the object. */
  objectId: string;
  /** The element under the pointer, or `null` when the pointer left the content or the object stopped being interactive. */
  element: KritzelObjectElementInfo | null;
  /** Whether the object is picking elements. While picking, `element` honors the picking `selector`. */
  isPicking: boolean;
}

/**
 * Emitted when the user clicks an element inside an interactive object's content. The click works as usual.
 * The content reports clicks, so untrusted content can report one without a real click while the object is selected.
 */
export interface KritzelObjectElementClickEvent extends KritzelObjectElementModifiers {
  /** ID of the object. */
  objectId: string;
  /** The clicked element: the innermost element under the pointer. */
  element: KritzelObjectElementInfo;
}

/**
 * Emitted when the user picks an element while the object is picking. The click doesn't reach the content.
 * The content reports picks, so untrusted content can report one without a real click while the object is picking:
 * don't treat a pick as the user's confirmation of something consequential.
 */
export interface KritzelObjectElementPickEvent extends KritzelObjectElementModifiers {
  /** ID of the object. */
  objectId: string;
  /** The picked element. */
  element: KritzelObjectElementInfo;
}

/**
 * An object whose content elements can be observed, picked, highlighted, queried and pointed at with an agent's
 * cursor. Implemented by `KritzelIframeObject`, whose page needs the `allow-scripts` sandbox token (the default)
 * for this. Highlights, picking and tracking are local and transient: they are neither serialized nor
 * synchronized to collaborators.
 */
export interface KritzelElementAwareObject {
  /** Whether the object is picking elements. */
  readonly isElementPicking: boolean;

  /**
   * Turns element picking on or off. While picking, the element under the pointer is highlighted and a click
   * picks it instead of reaching the content. Picking needs the object to be interactive, which it is while selected.
   */
  setElementPicking(enabled: boolean, options?: KritzelObjectElementPickingOptions): void;

  /** Replaces the element highlights. Pass an empty array to remove them. */
  setElementHighlights(highlights: KritzelObjectElementHighlight[]): void;

  /** Returns the current element highlights. */
  getElementHighlights(): KritzelObjectElementHighlight[];

  /**
   * Describes the elements that match a CSS selector, in document order.
   * Rejects if the selector is invalid, the object isn't mounted or its content doesn't respond.
   * @param limitOrOptions - Maximum number of elements (1 to 500, defaults to 100), or query options.
   */
  queryElements(selector: string, limitOrOptions?: number | KritzelObjectElementQueryOptions): Promise<KritzelObjectElementInfo[]>;

  /**
   * Performs an interaction on the first element that matches a CSS selector, as a user would: scrolls it into
   * view, checks that it is visible, enabled and not covered, then dispatches the events of the interaction.
   * Resolves with `completed: false` and a reason when it can't be performed, also when the object isn't mounted
   * or its content doesn't respond; rejects only for an invalid selector or interaction. Not undoable: the
   * content's own state changes, not the object. Optional, so objects written before it existed still qualify.
   */
  interactWithElement?(
    selector: string,
    interaction: KritzelObjectElementInteraction,
    options?: KritzelObjectElementInteractionOptions,
  ): Promise<KritzelObjectElementInteractionResult>;

  /** Starts reporting the visible position of the first element that matches a selector. Calls are reference-counted. */
  trackElement(selector: string): void;

  /** Undoes one `trackElement()` call for a selector. */
  untrackElement(selector: string): void;

  /**
   * Last known visible bounding box of a tracked element in content coordinates, or `null` if it hasn't been seen yet.
   * While the element can't be seen, e.g. while the content is regenerated, its last visible position is kept.
   */
  getTrackedElementRect(selector: string): KritzelObjectElementRect | null;

  /** Converts a point in content coordinates to world units in the object's local, unrotated space, relative to its top-left corner. */
  contentToObjectLocal(point: KritzelPoint): KritzelPoint;

  /** Re-reads the element highlight colors from the theme. Called by the engine when the theme changes. */
  refreshElementTheme(): void;

  /**
   * Takes over highlights, picking and tracked elements from an instance with the same id that this object replaces,
   * e.g. when a workspace's objects are replaced. Called by the core after the previous instance was unmounted.
   */
  adoptElementStateFrom?(previous: unknown): void;
}
